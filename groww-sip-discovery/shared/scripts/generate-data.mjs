// Generates shared/src/data/*.ts from the Phase 2 research outputs (research/data/phase2/*.json).
// Re-run after any Phase 2 rebuild:  pnpm generate:data
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const SRC = resolve(here, '../../../research/data/phase2')
const OUT = resolve(here, '../src/data')
mkdirSync(OUT, { recursive: true })

const read = (f) => JSON.parse(readFileSync(join(SRC, f), 'utf8'))
const pick = (o, keys) => Object.fromEntries(keys.map((k) => [k, o[k]]))

const HEADER = '// GENERATED by scripts/generate-data.mjs from research/data/phase2 — do not edit by hand.\n'

function emit(file, typeImport, constName, typeAnnotation, value) {
  const body = `${HEADER}import type { ${typeImport.names.join(', ')} } from '${typeImport.from}'\n\n` +
    `export const ${constName}: ${typeAnnotation} = ${JSON.stringify(value, null, 2)}\n`
  writeFileSync(join(OUT, file), body, 'utf8')
  console.log(`wrote src/data/${file}`)
}

const summary = read('corpus_summary.json')
emit('corpusSummary.ts', { names: ['CorpusSummary'], from: '../types/corpus' }, 'CORPUS_SUMMARY', 'CorpusSummary',
  pick(summary, ['totalRaw', 'rawPerChannel', 'afterRuleFilter', 'removedOnAnalystReview', 'totalFiltered', 'filteredPerChannel',
    'filteredPerLanguage', 'primaryResearch', 'noFrictionRecordIds']))

emit('verbatims.ts', { names: ['Verbatim'], from: '../types/corpus' }, 'VERBATIMS', 'Verbatim[]', read('verbatims.json'))

emit('frictionThemes.ts', { names: ['FrictionTheme'], from: '../types/corpus' }, 'FRICTION_THEMES', 'FrictionTheme[]',
  read('friction_themes.json').map((t) =>
    pick(t, ['id', 'name', 'summary', 'recordCount', 'severityScores', 'sebiRestricted', 'platformDependent', 'recordIds'])))

emit('discoveryAnswers.ts', { names: ['DiscoveryAnswer'], from: '../types/corpus' }, 'DISCOVERY_ANSWERS', 'DiscoveryAnswer[]',
  read('discovery_answers.json'))

emit('goldenSet.ts', { names: ['GoldenSetItem'], from: '../types/golden' }, 'GOLDEN_SET', 'GoldenSetItem[]', read('golden_set.json'))

emit('correctionCaseStudies.ts', { names: ['CorrectionCaseStudy'], from: '../types/golden' }, 'CORRECTION_CASE_STUDIES',
  'CorrectionCaseStudy[]', read('correction_case_studies.json'))

emit('quickLoadChips.ts', { names: ['QuickLoadChip'], from: '../types/corpus' }, 'QUICK_LOAD_CHIPS', 'QuickLoadChip[]',
  read('quick_load_chips.json'))
